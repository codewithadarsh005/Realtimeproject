'use strict';

const mongoose = require('mongoose');

/**
 * ThreatStats
 * Single-document collection that holds running totals.
 * Updated automatically via ScanHistory post-save hook.
 * Can also be rebuilt from scratch via ThreatStats.rebuild().
 */
const threatStatsSchema = new mongoose.Schema(
  {
    totalScans: {
      type: Number,
      default: 0,
      min: [0, 'totalScans cannot be negative'],
    },

    phishingDetected: {
      type: Number,
      default: 0,
      min: [0, 'phishingDetected cannot be negative'],
    },

    safeCount: {
      type: Number,
      default: 0,
      min: [0, 'safeCount cannot be negative'],
    },

    suspiciousCount: {
      type: Number,
      default: 0,
      min: [0, 'suspiciousCount cannot be negative'],
    },
  },
  {
    // updatedAt managed manually so the hook can set it precisely;
    // createdAt still auto-generated by timestamps.
    timestamps: { createdAt: true, updatedAt: false },
    toJSON: {
      versionKey: false,
      transform(doc, ret) {
        delete ret._id;
        return ret;
      },
    },
  }
);

// ── Explicit updatedAt field (not managed by Mongoose timestamps) ──────────
threatStatsSchema.add({
  updatedAt: {
    type: Date,
    default: Date.now,
  },
});

// ── Static: get or create the single stats document ───────────────────────
threatStatsSchema.statics.getSingleton = async function () {
  let doc = await this.findOne();
  if (!doc) doc = await this.create({});
  return doc;
};

/**
 * Static: rebuild totals from scratch by aggregating ScanHistory.
 * Useful for data repair or initial seed.
 */
threatStatsSchema.statics.rebuild = async function () {
  const ScanHistory = mongoose.model('ScanHistory');

  const [total, phishing, safe, suspicious] = await Promise.all([
    ScanHistory.countDocuments(),
    ScanHistory.countDocuments({ result: 'phishing' }),
    ScanHistory.countDocuments({ result: 'safe' }),
    ScanHistory.countDocuments({ result: 'suspicious' }),
  ]);

  return this.findOneAndUpdate(
    {},
    {
      $set: {
        totalScans:       total,
        phishingDetected: phishing,
        safeCount:        safe,
        suspiciousCount:  suspicious,
        updatedAt:        new Date(),
      },
    },
    { upsert: true, new: true }
  );
};

module.exports = mongoose.model('ThreatStats', threatStatsSchema);
